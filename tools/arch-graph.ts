// `npm run arch:graph` (issue #148): the engine\src module graph, one node per module, as a Mermaid
// block in docs\architecture\modules.md. GitHub renders Mermaid blocks in Markdown files [handle:
// https://docs.github.com/en/get-started/writing-on-github/working-with-advanced-formatting/creating-diagrams, read 2026-10-12];
// that page names no standalone .mmd file, so the graph is not written as one.
// The edges come from dependency-cruiser with the gate's own config, collapsed to modules. Its own
// mermaid reporter nests engine > src > module subgraphs with unlabelled nodes, so the flowchart is
// written here from its JSON.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

type Collapsed = { modules: { source: string; dependencies: { resolved: string }[] }[] };

const root = path.resolve(import.meta.dirname, "..");
const bin = path.join(root, "node_modules", "dependency-cruiser", "bin", "dependency-cruiser.mjs"); // a root devDependency

const json = execFileSync(
  process.execPath,
  [bin, "engine/src", "--config", ".dependency-cruiser.cjs", "--include-only", "^engine/src/", "--collapse", "^engine/src/[^/]+/", "--output-type", "json"],
  { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
const name = (p: string) => p.replace(/^engine\/src\/|\/$/g, "");
const lines = ["flowchart LR"];
for (const m of (JSON.parse(json) as Collapsed).modules.sort((a, b) => a.source.localeCompare(b.source))) {
  const deps = [...new Set(m.dependencies.map((d) => d.resolved))].filter((d) => d !== m.source).sort();
  lines.push(`  ${name(m.source)}`, ...deps.map((d) => `  ${name(m.source)} --> ${name(d)}`));
}

const out = path.join(root, "docs", "architecture", "modules.md");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  "# engine\\src module graph\n\n" +
    "Generated by `npm run arch:graph`; do not edit. One node per module of the CLAUDE.md \"Module Map\", one arrow per module it imports. " +
    "Arrows into `mcp` from modules other than `devtools` are imports of `mcp/errors.ts` only (rule `mcp-errors-only`).\n\n" +
    "```mermaid\n" + lines.join("\n") + "\n```\n",
);
console.log(`wrote ${path.relative(root, out)}`);
